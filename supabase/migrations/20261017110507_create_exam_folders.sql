/*
# Create exam folders (Windows Explorer-style hierarchy for exams)

1. New Tables
- `exam_folders` — hierarchical folders used to organize exams (e.g. Khối 10 > Tiếng Nhật > JLPT N2).
  - `id` (text, primary key) — generated by the app
  - `parent_id` (text, nullable) — references `exam_folders.id`; NULL = top-level folder
  - `name` (text, not null) — folder name
  - `description` (text, nullable)
  - `color` (text, nullable) — visual color key chosen in UI
  - `sort_order` (integer, default 0)
  - `created_by` (text, nullable) — username of creator (app-level auth)
  - `created_at` / `updated_at` (timestamptz)
  - `archived_at` (timestamptz, nullable) — soft delete / archive support

2. Modified Tables
- `exams` — added `folder_id` (text, nullable) referencing `exam_folders(id) ON DELETE SET NULL`.
  Existing exams keep `folder_id = NULL` and appear at "Trang chủ" (unfiled). No data is moved or lost.

3. Security
- RLS enabled on `exam_folders`.
- Policies match the app's existing access model (app-level auth in `app_users`, clients use the
  anon key): full CRUD for anon + authenticated, same as `exams`, `classes`, `subjects` tables.
- `ON DELETE SET NULL` for `exams.folder_id` guarantees deleting a folder never deletes exams.
- `ON DELETE CASCADE` for `exam_folders.parent_id` (delete is only reachable from UI for folders
  the user explicitly confirmed).

4. Notes
- No fixed grade/level structure — teachers create any folder tree they need.
- Cycle prevention (moving a folder into its own descendant) is enforced in the app's Move dialog.
*/
CREATE TABLE IF NOT EXISTS exam_folders (
  id text PRIMARY KEY,
  parent_id text REFERENCES exam_folders(id) ON DELETE CASCADE,
  name text NOT NULL,
  description text,
  color text,
  sort_order integer NOT NULL DEFAULT 0,
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  archived_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_exam_folders_parent ON exam_folders(parent_id);

ALTER TABLE exam_folders ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_read_exam_folders" ON exam_folders;
CREATE POLICY "anon_read_exam_folders" ON exam_folders
  FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_exam_folders" ON exam_folders;
CREATE POLICY "anon_insert_exam_folders" ON exam_folders
  FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_exam_folders" ON exam_folders;
CREATE POLICY "anon_update_exam_folders" ON exam_folders
  FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_exam_folders" ON exam_folders;
CREATE POLICY "anon_delete_exam_folders" ON exam_folders
  FOR DELETE TO anon, authenticated USING (true);

ALTER TABLE exams ADD COLUMN IF NOT EXISTS folder_id text REFERENCES exam_folders(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_exams_folder ON exams(folder_id);
